# muzzle points (first pixel past the bore, card coordinates) and grip points for reference
CARDS = {
    'revolver': {'grid': REVOLVER, 'muzzle': [47, 8]},
    'rifle': {'grid': RIFLE, 'muzzle': [47, 9]},
    'laser': {'grid': LASER, 'muzzle': [47, 9]},
}


def card_parts():
    out = {}
    for k, v in CARDS.items():
        rows = [r.strip() for r in v['grid'].strip('\n').split('\n')]
        bad = [(i, len(r)) for i, r in enumerate(rows) if len(r) != 48]
        assert not bad and len(rows) == 24, (k, bad, len(rows))
        out[k] = Part(v['grid'], GT, name='card_' + k)
    return out
