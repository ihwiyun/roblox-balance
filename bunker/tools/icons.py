def blank(): return [['.'] * 16 for _ in range(16)]
def coin():
    g = blank(); cx = cy = 7.5
    for y in range(16):
        for x in range(16):
            d = math.hypot(x - cx, y - cy)
            if d <= 7.4: g[y][x] = 'Y'
    for y in range(16):
        for x in range(16):
            if g[y][x] == '.': continue
            d = math.hypot(x - cx, y - cy)
            if d > 6.6: g[y][x] = 'o'
            elif d > 5.6: g[y][x] = 'y' if (x - cx) + (y - cy) > -2 else 'Y'
            else:
                if (x - cx) + (y - cy) > 6.5: g[y][x] = 'y'
    # light rim at top-left, dark rim at bottom-right
    for y in range(16):
        for x in range(16):
            if g[y][x] in 'yY':
                d = math.hypot(x - cx, y - cy)
                if 5.6 < d <= 6.6 and (x - cx) + (y - cy) < -5: g[y][x] = 'W'
                if 5.6 < d <= 6.6 and (x - cx) + (y - cy) > 5: g[y][x] = 'u'
    # an embossed "$"
    dollar = ['..u..', '.uuuu', 'u.u..', '.uuu.', '..u.u', 'uuuu.', '..u..']
    for j, row in enumerate(dollar):
        for i, ch in enumerate(row):
            if ch == 'u': g[4 + j][5 + i + 1] = 'u'
    g[5][7] = 'u'
    for (x, y) in [(4, 4), (5, 3), (4, 5)]: g[y][x] = 'W'
    return [''.join(r) for r in g]
